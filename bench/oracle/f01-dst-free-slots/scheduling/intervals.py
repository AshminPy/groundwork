def merge(intervals):
    """Merge (start, end) intervals: sorted, with overlapping or touching intervals joined."""
    out = []
    for s, e in sorted(intervals):
        if out and s <= out[-1][1]:
            out[-1] = (out[-1][0], max(out[-1][1], e))
        else:
            out.append((s, e))
    return out
